export const APPLICATION_FEEDBACK_VERSION = 'application_feedback.v2';
export const APPLICATION_RESPONSE_BANDS = [
  'strong',
  'developing',
  'needs_review',
] as const;

export type ApplicationResponseBand =
  (typeof APPLICATION_RESPONSE_BANDS)[number];

export type LegacyApplicationResponseBand =
  'mostly_good' | 'partial' | 'weak' | 'insufficient_evidence';

/** Historical grades are mapped for display without rewriting stored feedback. */
export function normaliseApplicationResponseBand(
  value: unknown,
): ApplicationResponseBand {
  switch (value) {
    case 'strong':
      return 'strong';
    case 'developing':
    case 'mostly_good':
    case 'partial':
      return 'developing';
    default:
      return 'needs_review';
  }
}

/** Only Portal's authenticated service may supply the authored question. */
export interface ApplicationAssessmentRequest {
  externalCourseId: string;
  question: string;
  answer: string;
  locale: 'en-GB' | 'zh-CN';
  userId: string;
  evaluationId: string;
}

export interface ApplicationFeedback {
  schemaVersion: typeof APPLICATION_FEEDBACK_VERSION;
  overallBand: ApplicationResponseBand;
  whatYouDidWell: string[];
  areasToImprove: string[];
  needsReview: boolean;
  reviewReason: string | null;
}

export type ApplicationReferenceAnswer =
  | { status: 'available'; contentMarkdown: string; sourceTitle: string }
  | { status: 'unavailable'; contentMarkdown: null; sourceTitle: null };

/** Answer and reference are attached by services, never generated by the judge. */
export interface ApplicationAssessmentResult {
  evaluationId: string;
  status: 'evaluated' | 'needs_review';
  feedback: ApplicationFeedback;
  yourAnswer: string;
  referenceAnswer: ApplicationReferenceAnswer;
  releaseId: string;
}

export class InvalidApplicationFeedbackError extends Error {
  constructor() {
    super('INVALID_APPLICATION_FEEDBACK');
  }
}

function shortText(value: unknown): value is string {
  return (
    typeof value === 'string' && value.trim().length > 0 && value.length <= 2000
  );
}

function feedbackList(value: unknown, maximum: number): value is string[] {
  return (
    Array.isArray(value) &&
    value.length <= maximum &&
    Array.from(value).every(shortText)
  );
}

export function parseApplicationFeedback(value: unknown): ApplicationFeedback {
  const invalid = () => {
    throw new InvalidApplicationFeedbackError();
  };
  if (!value || typeof value !== 'object' || Array.isArray(value)) invalid();
  const record = value as Record<string, unknown>;
  const keys = [
    'schemaVersion',
    'overallBand',
    'whatYouDidWell',
    'areasToImprove',
    'needsReview',
    'reviewReason',
  ];
  if (
    Object.keys(record).length !== keys.length ||
    !keys.every((key) => Object.hasOwn(record, key)) ||
    record.schemaVersion !== APPLICATION_FEEDBACK_VERSION ||
    !APPLICATION_RESPONSE_BANDS.some((band) => band === record.overallBand) ||
    !feedbackList(record.whatYouDidWell, 3) ||
    !feedbackList(record.areasToImprove, 2) ||
    typeof record.needsReview !== 'boolean' ||
    (record.needsReview
      ? !shortText(record.reviewReason) || record.overallBand !== 'needs_review'
      : record.reviewReason !== null)
  ) {
    invalid();
  }
  return {
    schemaVersion: APPLICATION_FEEDBACK_VERSION,
    overallBand: record.overallBand as ApplicationResponseBand,
    whatYouDidWell: [...(record.whatYouDidWell as string[])],
    areasToImprove: [...(record.areasToImprove as string[])],
    needsReview: record.needsReview as boolean,
    reviewReason: record.reviewReason as string | null,
  };
}
